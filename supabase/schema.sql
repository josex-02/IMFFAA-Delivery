-- Importante:
-- 1) No permitas que un usuario cliente se cambie su propio role a admin.
-- 2) El alta de perfiles/roles debe hacerse con trigger o función segura del servidor.
-- 3) La compra real debe usar una función transaccional/RPC que valide stock y permisos
--    y descuente inventario atómicamente; no confíes en el total calculado por Flutter.
-- 4) Guarda comprobantes e imágenes de identidad en buckets privados de Storage.

-- Crea perfil de cliente al registrar usuario en Supabase Auth.
create or replace function public.handle_new_user_profile()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, full_name, id_number, phone, role)
  values (new.id, coalesce(new.raw_user_meta_data->>'full_name', ''), new.raw_user_meta_data->>'id_number', new.raw_user_meta_data->>'phone', 'cliente')
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created_profile on auth.users;
create trigger on_auth_user_created_profile
after insert on auth.users
for each row execute procedure public.handle_new_user_profile();

-- Impide que un usuario se otorgue el rol admin modificando su propio perfil.
create or replace function public.prevent_self_role_escalation()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if auth.uid() = old.id and new.role is distinct from old.role and not public.is_admin() then
    raise exception 'No está permitido cambiar el rol propio';
  end if;
  return new;
end;
$$;

drop trigger if exists protect_profile_role on public.profiles;
create trigger protect_profile_role
before update on public.profiles
for each row execute procedure public.prevent_self_role_escalation();


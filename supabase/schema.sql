-- No se incluye ninguna clave de proyecto en el código de Flutter.

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null default '',
  id_number text,
  phone text,
  role text not null default 'cliente' check (role in ('cliente', 'admin')),
  created_at timestamptz not null default now()
);

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name text not null,
  description text not null default '',
  category text not null default 'Accesorios',
  gender text not null default 'Unisex',
  image_url text,
  price integer not null check (price >= 0),
  stock integer not null default 0 check (stock >= 0),
  colors text[] not null default '{}',
  sizes text[] not null default '{}',
  features text[] not null default '{}',
  requires_authorization boolean not null default false,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- Columnas aditivas para catálogo ampliado; no modifican credenciales ni conexión.
alter table public.products add column if not exists gender text not null default 'Unisex';
alter table public.products add column if not exists features text[] not null default '{}';

create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete restrict,
  customer_name text not null,
  customer_email text not null,
  phone text not null,
  delivery_address text not null,
  payment_method text not null,
  status text not null default 'recibido' check (status in ('recibido', 'preparando', 'entregado')),
  subtotal integer not null check (subtotal >= 0),
  shipping integer not null default 0 check (shipping >= 0),
  total integer not null check (total >= 0),
  receipt_path text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.order_items (
  id bigint generated by default as identity primary key,
  order_id uuid not null references public.orders(id) on delete cascade,
  product_id bigint references public.products(id) on delete set null,
  product_name text not null,
  unit_price integer not null check (unit_price >= 0),
  quantity integer not null check (quantity > 0),
  color text not null default '',
  size text not null default '',
  line_total integer not null check (line_total >= 0)
);

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.profiles p
    where p.id = auth.uid() and p.role = 'admin'
  );
$$;

alter table public.profiles enable row level security;
alter table public.products enable row level security;
alter table public.orders enable row level security;
alter table public.order_items enable row level security;

-- Perfiles: cada usuario ve/edita su perfil; solo admin puede administrar roles.
drop policy if exists "profiles read own or admin" on public.profiles;
create policy "profiles read own or admin" on public.profiles for select to authenticated
using (id = auth.uid() or public.is_admin());
drop policy if exists "profiles update own non-role fields" on public.profiles;
create policy "profiles update own non-role fields" on public.profiles for update to authenticated
using (id = auth.uid() or public.is_admin())
with check (id = auth.uid() or public.is_admin());

-- Catálogo público de solo lectura; cambios reservados al admin.
drop policy if exists "active products public read" on public.products;
create policy "active products public read" on public.products for select to anon, authenticated
using (active = true or public.is_admin());
drop policy if exists "admin manages products" on public.products;
create policy "admin manages products" on public.products for all to authenticated
using (public.is_admin()) with check (public.is_admin());

-- El cliente solo consulta sus pedidos. Solo admin cambia estados.
drop policy if exists "users read own orders or admin" on public.orders;
create policy "users read own orders or admin" on public.orders for select to authenticated
using (user_id = auth.uid() or public.is_admin());
drop policy if exists "users create own orders" on public.orders;
create policy "users create own orders" on public.orders for insert to authenticated
with check (user_id = auth.uid());
drop policy if exists "admin updates orders" on public.orders;
create policy "admin updates orders" on public.orders for update to authenticated
using (public.is_admin()) with check (public.is_admin());

drop policy if exists "users read own order items or admin" on public.order_items;
create policy "users read own order items or admin" on public.order_items for select to authenticated
using (exists (select 1 from public.orders o where o.id = order_id and (o.user_id = auth.uid() or public.is_admin())));
drop policy if exists "users insert own order items or admin" on public.order_items;
create policy "users insert own order items or admin" on public.order_items for insert to authenticated
with check (exists (select 1 from public.orders o where o.id = order_id and (o.user_id = auth.uid() or public.is_admin())));

create or replace function public.place_order(
  p_customer_name text,
  p_customer_email text,
  p_phone text,
  p_delivery_address text,
  p_payment_method text,
  p_items jsonb
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_user_id uuid := auth.uid();
  v_order_id uuid;
  v_created_at timestamptz := now();
  v_subtotal integer := 0;
  v_shipping integer := 80;
  v_item record;
  v_product_name text;
  v_unit_price integer;
  v_remaining_stock integer;
  v_order_lines jsonb := '[]'::jsonb;
begin
  if v_user_id is null then
    raise exception 'Debes iniciar sesión para registrar el pedido.';
  end if;
  if nullif(trim(p_customer_name), '') is null
      or nullif(trim(p_customer_email), '') is null
      or nullif(trim(p_phone), '') is null
      or nullif(trim(p_delivery_address), '') is null
      or nullif(trim(p_payment_method), '') is null then
    raise exception 'Completa los datos del pedido.';
  end if;
  if jsonb_typeof(p_items) is distinct from 'array' then
    raise exception 'El pedido debe incluir una lista de productos.';
  end if;
  if jsonb_array_length(p_items) = 0 then
    raise exception 'El pedido debe incluir al menos un producto.';
  end if;

  for v_item in
    select product_id, quantity, coalesce(color, '') as color,
        coalesce(size, '') as size
    from jsonb_to_recordset(p_items) as item(
      product_id bigint,
      quantity integer,
      color text,
      size text
    )
  loop
    if v_item.product_id is null or v_item.quantity is null
        or v_item.quantity <= 0 then
      raise exception 'El producto o la cantidad del pedido no son válidos.';
    end if;

    update public.products
    set stock = stock - v_item.quantity
    where id = v_item.product_id
      and active = true
      and stock >= v_item.quantity
    returning name, price, stock
      into v_product_name, v_unit_price, v_remaining_stock;

    if not found then
      raise exception 'Stock insuficiente para el producto %.',
          v_item.product_id;
    end if;

    v_subtotal := v_subtotal + (v_unit_price * v_item.quantity);
    v_order_lines := v_order_lines || jsonb_build_array(jsonb_build_object(
      'product_id', v_item.product_id,
      'product_name', v_product_name,
      'unit_price', v_unit_price,
      'quantity', v_item.quantity,
      'color', v_item.color,
      'size', v_item.size,
      'line_total', v_unit_price * v_item.quantity,
      'stock_remaining', v_remaining_stock
    ));
  end loop;

  insert into public.orders (
    user_id, customer_name, customer_email, phone, delivery_address,
    payment_method, status, subtotal, shipping, total, created_at
  )
  values (
    v_user_id, trim(p_customer_name), trim(p_customer_email), trim(p_phone),
    trim(p_delivery_address), trim(p_payment_method), 'preparing',
    v_subtotal, v_shipping, v_subtotal + v_shipping, v_created_at
  )
  returning id into v_order_id;

  insert into public.order_items (
    order_id, product_id, product_name, unit_price, quantity, color, size,
    line_total
  )
  select v_order_id, item.product_id, item.product_name, item.unit_price,
      item.quantity, item.color, item.size, item.line_total
  from jsonb_to_recordset(v_order_lines) as item(
    product_id bigint,
    product_name text,
    unit_price integer,
    quantity integer,
    color text,
    size text,
    line_total integer
  );

  return jsonb_build_object(
    'id', v_order_id,
    'subtotal', v_subtotal,
    'shipping', v_shipping,
    'total', v_subtotal + v_shipping,
    'created_at', v_created_at,
    'lines', v_order_lines
  );
end;
$$;

revoke all on function public.place_order(text, text, text, text, text, jsonb)
  from public, anon;
grant execute on function public.place_order(text, text, text, text, text, jsonb)
  to authenticated;

